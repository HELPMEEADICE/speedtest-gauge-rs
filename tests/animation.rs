/// 阶跃响应。
///
/// 源码注释说 `omega = 21.4` "settles in ~0.2 s"，实测口径是**1% 收敛**（|Δ| < 2.7° of 270°）
/// —— node 与 Rust 都给 0.267 s。而 `is_settled` 用的 0.02° 容差实际要到 0.367 s。
/// 两个口径都断言，避免把"体感 200ms"当成"0.02° 在 200ms 内"。
#[test]
fn spring_step_response_settles_around_200ms() {
    let mut motion = NeedleMotion::default();
    motion.set_target(135.0, SetTargetOpts::default());
    let dt = 1.0 / 60.0;
    let mut elapsed = 0.0;
    let mut one_percent_at: Option<f64> = None;
    let mut angle_settled_at: Option<f64> = None;
    let mut fully_settled_at: Option<f64> = None;
    for _ in 0..120 {
        motion.step(dt);
        elapsed += dt;
        if one_percent_at.is_none() && (motion.angle - 135.0).abs() < 2.7 {
            one_percent_at = Some(elapsed);
        }
        if angle_settled_at.is_none() && (motion.angle - 135.0).abs() < 0.02 {
            angle_settled_at = Some(elapsed);
        }
        if fully_settled_at.is_none() && motion.is_settled() {
            fully_settled_at = Some(elapsed);
        }
    }
    println!(
        "spring step(-135 -> 135): 1% at {:?}, |Δ|<0.02 at {:?}, is_settled at {:?}, final angle {:.6}, velocity {:.4}",
        one_percent_at, angle_settled_at, fully_settled_at, motion.angle, motion.velocity
    );
    // 1% 口径：与源码注释的 "~0.2 s" 对齐（实测 0.267 s）
    let one_percent_at = one_percent_at.expect("1% 收敛未达成");
    assert!(one_percent_at <= 0.30, "1% 收敛过慢: {one_percent_at} s");
    assert!(
        one_percent_at >= 0.05,
        "1% 收敛过快，参数可能不对: {one_percent_at} s"
    );
    // 0.02° 口径：实测 0.367 s
    let angle_settled_at = angle_settled_at.expect("阶跃响应没有进入 0.02° 容差");
    assert!(angle_settled_at <= 0.45, "收敛过慢: {angle_settled_at} s");
    assert!(
        fully_settled_at.expect("没有进入 is_settled") <= 0.6,
        "is_settled 过慢: {fully_settled_at:?}"
    );
    assert!((motion.angle - 135.0).abs() < 0.02);
}

/// 变步长（0.05 与 0.0166 混合）不得发散：返回值必须有限且落在 ±137 内。
#[test]
fn mixed_dt_input_stays_stable() {
    let mut motion = NeedleMotion::default();
    let steps = [0.05, 0.0166, 0.05, 0.0166, 0.05, 0.0166];
    let targets = [135.0, -135.0, 120.0, 10.0, 135.0, -30.0];
    let mut worst = 0.0f64;
    for round in 0..400 {
        let dt = steps[round % steps.len()];
        let target = targets[(round / 7) % targets.len()];
        motion.set_target(target, SetTargetOpts::default());
        let painted = motion.step(dt);
        assert!(painted.is_finite(), "第 {round} 步返回了非有限值");
        assert!(
            (-137.0..=137.0).contains(&painted),
            "第 {round} 步越界: {painted}"
        );
        assert!(motion.angle.is_finite() && motion.velocity.is_finite());
        assert!(
            motion.angle.abs() <= 200.0,
            "内部角漂移: {} (第 {round} 步)",
            motion.angle
        );
        worst = worst.max(painted.abs());
    }
    println!(
        "mixed-dt: 400 步后 angle={:.4} velocity={:.4} |painted|max={worst:.4}",
        motion.angle, motion.velocity
    );
}

