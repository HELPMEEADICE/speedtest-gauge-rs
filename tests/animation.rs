#[test]
fn step_clock_does_not_touch_real_time() {
    let mut clock = StepClock::new(1_000.0);
    assert_eq!(clock.tick(1_016.0), 0.016);
    assert_eq!(clock.last_ms(), 1_016.0);
    // 落后太多 ⇒ 被 clamp 到 0.05
    assert_eq!(clock.tick(6_016.0), 0.05);
    // 时间倒退 ⇒ 负 dt（源码同样不夹下限）
    assert!(clock.tick(6_000.0) < 0.0);
    clock.rebase(9_000.0);
    assert_eq!(clock.tick(9_016.0), 0.016);

    // 不依赖真实时钟：连续喂同一时间戳，dt 恒为 0
    let mut fixed = StepClock::new(5.0);
    assert_eq!(fixed.tick(5.0), 0.0);
}
