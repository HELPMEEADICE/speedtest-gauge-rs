/// 附录 B12：spring 模式下 `reset()` 的归位 tween **不可**被 `set_target` 打断。
#[test]
fn b12_reset_is_not_interrupted_by_set_target() {
    let mut motion = NeedleMotion::default();
    motion.set_target(90.0, SetTargetOpts::snap());
    assert_eq!(motion.angle, 90.0);

    motion.reset();
    assert!(motion.is_resetting());

    // 归位途中来一个新样本：target 改了，但归位仍在跑
    motion.set_target(0.0, SetTargetOpts::default());
    assert_eq!(motion.target, 0.0);
    assert!(motion.is_resetting());

    let dt = 1.0 / 60.0;
    let mut elapsed = 0.0;
    while elapsed < 0.45 {
        motion.step(dt);
        elapsed += dt;
    }
    println!(
        "B12 @{elapsed:.3}s: angle={:.4} target={:.4} resetting={}",
        motion.angle,
        motion.target,
        motion.is_resetting()
    );
    // 指针还在往 -135 走（而不是朝新 target 0 走）
    assert!(
        motion.angle < -100.0,
        "归位被打断了: angle={}",
        motion.angle
    );
    assert!(motion.is_resetting());

    // 归位结束后才开始追新 target
    while elapsed < 1.6 {
        motion.step(dt);
        elapsed += dt;
    }
    assert!(!motion.is_resetting());
    assert!(
        (motion.angle - 0.0).abs() < 0.02,
        "归位结束后没有追上 target: {}",
        motion.angle
    );

    // snap 也不清 springResetTween
    motion.reset();
    motion.set_target(45.0, SetTargetOpts::snap());
    assert_eq!(motion.angle, 45.0);
    assert!(motion.is_resetting(), "snap 不应清除归位 tween（B12）");
}

#[test]
fn tween_mode_restarts_from_current_angle() {
    let mut motion = NeedleMotion::new(NeedleConfig {
        mode: MotionMode::Tween,
        ..NeedleConfig::default()
    });
    motion.set_target(0.0, SetTargetOpts::default());
    let dt = 1.0 / 60.0;
    // 走 12 帧 ≈ 0.2 s：easeOut 到终点
    for _ in 0..12 {
        motion.step(dt);
    }
    assert!(
        (motion.angle - 0.0).abs() < 1.0,
        "200ms tween 未接近终点: {}",
        motion.angle
    );
    // 再补一帧，raw >= 1 ⇒ 精确落点
    motion.step(dt);
    assert_eq!(motion.angle, 0.0);

    // 重定向：从**当前角**重开，且时长重置为完整 200 ms
    motion.set_target(135.0, SetTargetOpts::default());
    let half = motion.step(0.1);
    let at_half = motion.angle;
    assert!(
        at_half > 0.0 && at_half < 135.0,
        "重定向后中点异常: {at_half}"
    );
    // easeOut(0.5) ≈ 0.8 ⇒ 0 + 135*0.8 ≈ 108
    assert!(
        at_half > 90.0,
        "easeOut 中点应超过 90°: {at_half} / painted {half}"
    );
}

